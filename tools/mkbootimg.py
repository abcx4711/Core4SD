#!/usr/bin/env python3
"""Builds src/bootimg.h: the built-in menu disk of the Core4SD
firmware. Block 0 = boot block, blocks 1.. = the browser (loaded at $2000).

usage: mkbootimg.py boot.bin CORE4SD.SYSTEM > bootimg.h
"""
import sys

boot = open(sys.argv[1], "rb").read()
prog = open(sys.argv[2], "rb").read()
if len(boot) != 512:
    sys.exit("boot block must be exactly 512 bytes")
nblk = (len(prog) + 511) // 512
img = boot + prog + bytes(nblk * 512 - len(prog))
blocks = len(img) // 512

out = []
out.append("/* Generated by tools/mkbootimg.py -- do not edit. */")
out.append("/* Menu disk: boot block + Core4SD SD-Browser (%d bytes). */" % len(prog))
out.append("#ifndef BOOTIMG_H")
out.append("#define BOOTIMG_H")
out.append("#include <avr/pgmspace.h>")
out.append("#define BOOTIMG_BLOCKS %d" % blocks)
out.append("static const uint8_t bootimg[%d] PROGMEM = {" % len(img))
for i in range(0, len(img), 16):
    out.append("    " + ", ".join("0x%02X" % b for b in img[i:i + 16]) + ",")
out.append("};")
out.append("#endif")
print("\n".join(out))
